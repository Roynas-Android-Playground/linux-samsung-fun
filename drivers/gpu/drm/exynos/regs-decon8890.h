#ifndef _REGS_DECON8890_H
#define _REGS_DECON8890_H

#define DECON8890_GLOBAL_CONTROL	0x0000
#define DECON8890_INTERRUPT_ENABLE	0x0040
#define DECON8890_INTERRUPT_PENDING	0x0048
#define DECON8890_SHADOW_UPDATE		0x0060
#define DECON8890_TRIGGER_CONTROL	0x0070
#define DECON8890_DISPIF_SIZE		0x00a0
#define DECON8890_WIN_CONTROL(n)	(0x0130 + (n) * 0x20)
#define DECON8890_WIN_START(n)		(0x0134 + (n) * 0x20)
#define DECON8890_WIN_END(n)		(0x0138 + (n) * 0x20)
#define DECON8890_WIN_COLORMAP(n)	(0x013c + (n) * 0x20)
#define DECON8890_WIN_START_TIME(n)	(0x0140 + (n) * 0x20)
#define DECON8890_WIN_PIXEL_COUNT(n)	(0x0144 + (n) * 0x20)
#define DECON8890_DATA_PATH_CONTROL	0x0230
#define DECON8890_FRAME_ID		0x02a0

#define DECON8890_GLOBAL_SRESET		BIT(28)
#define DECON8890_GLOBAL_COMMAND_MODE	BIT(8)
#define DECON8890_GLOBAL_URGENT		BIT(6)
#define DECON8890_GLOBAL_IDLE		BIT(5)
#define DECON8890_GLOBAL_RUN		BIT(4)
#define DECON8890_GLOBAL_ENABLE		BIT(1)
#define DECON8890_GLOBAL_ENABLE_F	BIT(0)

/* INTERRUPT_PENDING shares the INTERRUPT_ENABLE bit layout */
#define DECON8890_INT_DPU1		BIT(29)
#define DECON8890_INT_DPU0		BIT(28)
#define DECON8890_INT_VSTATUS		BIT(24)
#define DECON8890_INT_VSTATUS_SEL_VSA	BIT(20)
#define DECON8890_INT_RESOURCE_CONFLICT	BIT(18)
#define DECON8890_INT_EVEN_FRAME_START	BIT(17)
#define DECON8890_INT_ODD_FRAME_START	BIT(16)
#define DECON8890_INT_FRAME_DONE	BIT(12)
#define DECON8890_INT_FIFO_LEVEL	BIT(8)
#define DECON8890_INT_EN		BIT(0)

#define DECON8890_DISPIF_HEIGHT(v)	((v) << 16)
#define DECON8890_DISPIF_WIDTH(v)	((v) << 0)

#define DECON8890_WIN_ALPHA1(v)		(((v) & 0xff) << 24)
#define DECON8890_WIN_ALPHA0(v)		(((v) & 0xff) << 16)
#define DECON8890_WIN_CHMAP(v)		(((v) & 0x7) << 12)
#define DECON8890_WIN_CHMAP_MASK	GENMASK(14, 12)
#define DECON8890_WIN_FUNC(v)		(((v) & 0xf) << 8)
#define DECON8890_WIN_ALPHA_MUL		BIT(6)
#define DECON8890_WIN_ALPHA_SEL(v)	(((v) & 0x7) << 4)
#define DECON8890_WIN_MAPCOLOR		BIT(1)
#define DECON8890_WIN_ENABLE		BIT(0)

/* WIN_CONTROL.FUNC - Porter-Duff compositing selector */
#define DECON8890_PD_FUNC_COPY		0x1
#define DECON8890_PD_FUNC_SOURCE_OVER	0x3
/* WIN_CONTROL.ALPHA_SEL */
#define DECON8890_ALPHA_SEL_ALPHA0	0x0
#define DECON8890_ALPHA_SEL_BYAEN	0x2

#define DECON8890_WIN_POS_X(v)		(((v) & 0x1fff) << 0)
#define DECON8890_WIN_POS_Y(v)		(((v) & 0x1fff) << 16)

#define DECON8890_TRIGGER_AUTO_MASK	BIT(12)
#define DECON8890_TRIGGER_SW		BIT(8)
#define DECON8890_TRIGGER_HW_MASK	BIT(5)
#define DECON8890_TRIGGER_HW_ENABLE	BIT(4)

#define DECON8890_UPDATE_GLOBAL		BIT(31)
#define DECON8890_UPDATE_DPU		BIT(28)
#define DECON8890_UPDATE_MDNIE		BIT(24)
#define DECON8890_UPDATE_WIN(n)		BIT(n)
#define DECON8890_UPDATE_ALL_WIN	0xff

/*
 * Register snapshot the bootloader (uniLoader) leaves behind: MIC 1/2 on,
 * single DSI, command mode, window 0 on IDMA_G1 over cont_splash_mem.
 * DISPIF is 2560x720 because MIC compresses width before the interface.
 */
#define DECON8890_INHERITED_GLOBAL	0x00100133
#define DECON8890_INHERITED_IRQ_ENABLE	0x01141101
#define DECON8890_INHERITED_TRIGGER	0x00001010
#define DECON8890_INHERITED_PATH	0x00000009
#define DECON8890_INHERITED_SIZE	0x0a0002d0

#endif /* _REGS_DECON8890_H */
