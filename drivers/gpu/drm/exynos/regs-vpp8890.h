#ifndef _REGS_VPP8890_H
#define _REGS_VPP8890_H

#define VPP8890_ENABLE			0x000
#define VPP8890_IRQ			0x004
#define VPP8890_IN_CON			0x008
#define VPP8890_OUT_CON			0x00c
#define VPP8890_SRC_SIZE		0x010
#define VPP8890_SRC_OFFSET		0x014
#define VPP8890_IMG_SIZE		0x018
#define VPP8890_PINGPONG_UPDATE		0x01c
#define VPP8890_SCALED_SIZE		0x02c
#define VPP8890_QOS_LUT07_00		0x060
#define VPP8890_QOS_LUT15_08		0x064
#define VPP8890_BASE_ADDR_CON		0x070
#define VPP8890_BASE_ADDR_Y(n)		(0x074 + (n) * 0x4)
#define VPP8890_BASE_ADDR_CB(n)		(0x094 + (n) * 0x4)
#define VPP8890_YHPOSITION0		0x5b0
#define VPP8890_YVPOSITION0		0x5b4
#define VPP8890_CHPOSITION0		0x5b8
#define VPP8890_CVPOSITION0		0x5bc
#define VPP8890_DEADLOCK_NUM		0xa00
#define VPP8890_SMART_IF_PIXEL_NUM	0xa48
#define VPP8890_DYNAMIC_GATING_ENABLE	0xa54

#define VPP8890_ENABLE_OP_STATUS	BIT(2)
#define VPP8890_ENABLE_SFR_UPDATE_FORCE	BIT(4)
#define VPP8890_ENABLE_RT_PATH		BIT(16)
#define VPP8890_ENABLE_SRESET		BIT(24)

#define VPP8890_IRQ_ENABLE		BIT(0)
#define VPP8890_IRQ_FRAMEDONE_MASK	BIT(1)
#define VPP8890_IRQ_DEADLOCK_MASK	BIT(2)
#define VPP8890_IRQ_READ_ERROR_MASK	BIT(4)
#define VPP8890_IRQ_RESET_DONE_MASK	BIT(5)
#define VPP8890_IRQ_FRAMEDONE		BIT(16)
#define VPP8890_IRQ_DEADLOCK		BIT(17)
#define VPP8890_IRQ_READ_ERROR		BIT(19)
#define VPP8890_IRQ_RESET_DONE		BIT(20)
#define VPP8890_IRQ_STATUS_MASK		(VPP8890_IRQ_FRAMEDONE | VPP8890_IRQ_DEADLOCK | \
					 VPP8890_IRQ_READ_ERROR | VPP8890_IRQ_RESET_DONE)
#define VPP8890_IRQ_ALL_MASKED		0x37

#define VPP8890_IN_BLOCKING		BIT(3)
#define VPP8890_IN_CHROMA_STRIDE	BIT(4)
#define VPP8890_IN_AFBC		BIT(7)
#define VPP8890_IN_ROTATION_MASK	GENMASK(10, 8)
#define VPP8890_IN_FORMAT_MASK		GENMASK(15, 11)
#define VPP8890_IN_FORMAT_ARGB8888	(0 << 11)
#define VPP8890_IN_FORMAT_ABGR8888	(1 << 11)
#define VPP8890_IN_FORMAT_RGBA8888	(2 << 11)
#define VPP8890_IN_FORMAT_BGRA8888	(3 << 11)
#define VPP8890_IN_FORMAT_XRGB8888	(4 << 11)
#define VPP8890_IN_FORMAT_XBGR8888	(5 << 11)
#define VPP8890_IN_FORMAT_RGBX8888	(6 << 11)
#define VPP8890_IN_FORMAT_BGRX8888	(7 << 11)
#define VPP8890_IN_FORMAT_RGB565	(8 << 11)

#define VPP8890_OUT_CON_FRAME_ALPHA(v)	(((v) & 0xff) << 24)
#define VPP8890_OUT_CON_FRAME_ALPHA_MASK GENMASK(31, 24)

#define VPP8890_SIZE(w, h)		(((w) & 0x1fff) | (((h) & 0x1fff) << 16))
#define VPP8890_PINGPONG_REQUEST	BIT(0)

#define VPP8890_QOS_LUT_DEFAULT		0x44444444
#define VPP8890_DYNAMIC_GATING_ALL	0x3f

#endif /* _REGS_VPP8890_H */
