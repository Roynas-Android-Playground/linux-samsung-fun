#ifndef _REGS_VPP8890_H
#define _REGS_VPP8890_H

#define VPP8890_ENABLE			0x000
#define VPP8890_IRQ			0x004
#define VPP8890_IN_CON			0x008
#define VPP8890_OUT_CON			0x00c
#define VPP8890_SRC_SIZE		0x010
#define VPP8890_SRC_OFFSET		0x014
#define VPP8890_IMG_SIZE		0x018
#define VPP8890_PINGPONG_UPDATE		0x01c
#define VPP8890_CHROMINANCE_STRIDE	0x020
#define VPP8890_BLOCK_OFFSET		0x024
#define VPP8890_BLOCK_SIZE		0x028
#define VPP8890_SCALED_SIZE		0x02c
#define VPP8890_H_RATIO			0x044
#define VPP8890_V_RATIO			0x048
#define VPP8890_QOS_LUT07_00		0x060
#define VPP8890_QOS_LUT15_08		0x064
#define VPP8890_BASE_ADDR_CON		0x070
#define VPP8890_BASE_ADDR_Y0		0x074
#define VPP8890_BASE_ADDR_CB0		0x094
#define VPP8890_DEADLOCK_NUM		0xa00
#define VPP8890_SMART_IF_PIXEL_NUM	0xa48
#define VPP8890_DYNAMIC_GATING_ENABLE	0xa54
#define VPP8890_SHADOW_BASE_ADDR_Y	0xb74
#define VPP8890_SHADOW_BASE_ADDR_CB	0xb94

#define VPP8890_ENABLE_OP_STATUS	BIT(2)
#define VPP8890_ENABLE_RT_PATH		BIT(16)
#define VPP8890_ENABLE_SRESET		BIT(24)
#define VPP8890_ENABLE_CONFIG_MASK	(GENMASK(11, 8) | GENMASK(17, 16))
#define VPP8890_IRQ_ENABLE		BIT(0)
#define VPP8890_IRQ_FRAME_MASK		BIT(1)
#define VPP8890_IRQ_DEADLOCK_MASK	BIT(2)
#define VPP8890_IRQ_READ_ERROR_MASK	BIT(4)
#define VPP8890_IRQ_RESET_MASK		BIT(5)
#define VPP8890_IRQ_ALL_MASKED		0x37
#define VPP8890_IRQ_STATUS_MASK	(BIT(16) | BIT(17) | BIT(19) | BIT(20))
#define VPP8890_IRQ_CONFIG_MASK		GENMASK(5, 0)
#define VPP8890_BASE_CON_CONFIG_MASK	GENMASK(17, 16)
#define VPP8890_IN_BLOCKING		BIT(3)
#define VPP8890_IN_CHROMA_STRIDE	BIT(4)
#define VPP8890_IN_SCAN_MODE(v)	(((v) >> 5) & 0x3)
#define VPP8890_IN_AFBC			BIT(7)
#define VPP8890_IN_ROTATION(v)		(((v) >> 8) & 0x7)
#define VPP8890_IN_FORMAT(v)		(((v) >> 11) & 0x1f)
#define VPP8890_IN_BURST(v)		(((v) >> 24) & 0xf)
#define VPP8890_WIDTH(v)		((v) & 0x1fff)
#define VPP8890_HEIGHT(v)		(((v) >> 16) & 0x1fff)
#define VPP8890_SIZE(w, h)		((w) | ((h) << 16))
#define VPP8890_PINGPONG_REQUEST	BIT(0)

#define VPP8890_INHERITED_ENABLE	0x00000000
#define VPP8890_INHERITED_IRQ		0x00000037
#define VPP8890_INHERITED_IN_CON	0xff800000
#define VPP8890_INHERITED_OUT_CON	0xff000000
#define VPP8890_INHERITED_SIZE		0x0a0005a0
#define VPP8890_INHERITED_OFFSET	0x00000000
#define VPP8890_INHERITED_SCALED	0x00000000
#define VPP8890_INHERITED_RATIO		0x00000000
#define VPP8890_INHERITED_BASE_CON	0x0000000e
#define VPP8890_INHERITED_BASE		0xe2a00000
#define VPP8890_INHERITED_CB_BASE	0x00000000
#define VPP8890_INHERITED_DEADLOCK	0xffffffff
#define VPP8890_INHERITED_QOS		0x44444444
#define VPP8890_INHERITED_SMART_PIXELS	3686400
#define VPP8890_INHERITED_GATING	0x0000003f

#endif /* _REGS_VPP8890_H */
