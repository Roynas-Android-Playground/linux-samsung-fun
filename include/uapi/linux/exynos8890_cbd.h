#define EXYNOS8890_CBD_IOCTL_MODEM_OFF		_IO(EXYNOS8890_CBD_IOC_MAGIC, 0x20)
#define EXYNOS8890_CBD_IOCTL_MODEM_RESET		_IO(EXYNOS8890_CBD_IOC_MAGIC, 0x21)
#define EXYNOS8890_CBD_IOCTL_BOOT_ON		_IO(EXYNOS8890_CBD_IOC_MAGIC, 0x22)
#define EXYNOS8890_CBD_IOCTL_BOOT_OFF		_IO(EXYNOS8890_CBD_IOC_MAGIC, 0x23)
#define EXYNOS8890_CBD_IOCTL_BOOT_DONE		_IO(EXYNOS8890_CBD_IOC_MAGIC, 0x24)
#define EXYNOS8890_CBD_IOCTL_PROTOCOL_SUSPEND	_IO(EXYNOS8890_CBD_IOC_MAGIC, 0x25)
#define EXYNOS8890_CBD_IOCTL_PROTOCOL_RESUME	_IO(EXYNOS8890_CBD_IOC_MAGIC, 0x26)
#define EXYNOS8890_CBD_IOCTL_MODEM_STATUS	_IO(EXYNOS8890_CBD_IOC_MAGIC, 0x27)
#define EXYNOS8890_CBD_IOCTL_DL_START		_IO(EXYNOS8890_CBD_IOC_MAGIC, 0x28)
#define EXYNOS8890_CBD_IOCTL_FW_UPDATE		_IO(EXYNOS8890_CBD_IOC_MAGIC, 0x29)
#define EXYNOS8890_CBD_IOCTL_NET_SUSPEND		_IO(EXYNOS8890_CBD_IOC_MAGIC, 0x30)
#define EXYNOS8890_CBD_IOCTL_NET_RESUME		_IO(EXYNOS8890_CBD_IOC_MAGIC, 0x31)
#define EXYNOS8890_CBD_IOCTL_DUMP_START		_IO(EXYNOS8890_CBD_IOC_MAGIC, 0x32)
#define EXYNOS8890_CBD_IOCTL_DUMP_UPDATE		_IO(EXYNOS8890_CBD_IOC_MAGIC, 0x33)
#define EXYNOS8890_CBD_IOCTL_FORCE_CRASH		_IO(EXYNOS8890_CBD_IOC_MAGIC, 0x34)
#define EXYNOS8890_CBD_IOCTL_CP_UPLOAD		_IO(EXYNOS8890_CBD_IOC_MAGIC, 0x35)
#define EXYNOS8890_CBD_IOCTL_SET_TX_LINK		_IO(EXYNOS8890_CBD_IOC_MAGIC, 0x37)
#define EXYNOS8890_CBD_IOCTL_XMIT_BOOT		_IO(EXYNOS8890_CBD_IOC_MAGIC, 0x40)
#define EXYNOS8890_CBD_IOCTL_GET_SHMEM_INFO	_IO(EXYNOS8890_CBD_IOC_MAGIC, 0x41)
#define EXYNOS8890_CBD_IOCTL_LINK_RESET		_IO(EXYNOS8890_CBD_IOC_MAGIC, 0x44)
#define EXYNOS8890_CBD_IOCTL_GET_SRINFO		_IO(EXYNOS8890_CBD_IOC_MAGIC, 0x45)
#define EXYNOS8890_CBD_IOCTL_SET_SRINFO		_IO(EXYNOS8890_CBD_IOC_MAGIC, 0x46)
#define EXYNOS8890_CBD_IOCTL_LOG_DUMP		_IO(EXYNOS8890_CBD_IOC_MAGIC, 0x51)
#define EXYNOS8890_CBD_IOCTL_SECURITY_REQ	_IO(EXYNOS8890_CBD_IOC_MAGIC, 0x53)
#define EXYNOS8890_CBD_IOCTL_SHMEM_FULL_DUMP	_IO(EXYNOS8890_CBD_IOC_MAGIC, 0x54)
#define EXYNOS8890_CBD_IOCTL_RAMDUMP_START	_IO(EXYNOS8890_CBD_IOC_MAGIC, 0xce)
#define EXYNOS8890_CBD_IOCTL_RAMDUMP_STOP	_IO(EXYNOS8890_CBD_IOC_MAGIC, 0xcf)

enum exynos8890_cbd_boot_mode {
	EXYNOS8890_CBD_BOOT_NORMAL,
	EXYNOS8890_CBD_BOOT_DUMP,
	EXYNOS8890_CBD_BOOT_REINIT,
};

enum exynos8890_cbd_modem_state {
	EXYNOS8890_CBD_STATE_OFFLINE = 0,
	EXYNOS8890_CBD_STATE_CRASH_RESET,
	EXYNOS8890_CBD_STATE_CRASH_EXIT,
	EXYNOS8890_CBD_STATE_BOOTING,
	EXYNOS8890_CBD_STATE_ONLINE,
	EXYNOS8890_CBD_STATE_NV_REBUILDING,
	EXYNOS8890_CBD_STATE_LOADER_DONE,
	EXYNOS8890_CBD_STATE_SIM_ATTACH,
	EXYNOS8890_CBD_STATE_SIM_DETACH,
	EXYNOS8890_CBD_STATE_CRASH_WATCHDOG,
};

/* Layout is inherited from Samsung cbd/modem_v1. Do not reorder fields. */
struct exynos8890_cbd_firmware {
	__u64 binary;
	__u32 size;
	__u32 main_offset;
	__u32 boot_offset;
	__u32 mode;
	__u32 length;
} __attribute__((packed));

struct exynos8890_cbd_security_request {
	__u32 mode;
	__u32 boot_size;
	__u32 main_size;
	__u32 reserved;
} __attribute__((packed));

struct exynos8890_cbd_srinfo {
	__u32 size;
	__u8 data[];
} __attribute__((packed));

#endif /* _UAPI_LINUX_EXYNOS8890_CBD_H */
